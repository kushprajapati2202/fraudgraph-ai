"""Run the unchanged rule engine on an independent public dataset and report what it finds.

The dataset is IBM's "Transactions for Anti Money Laundering" (HI-Small), released under CDLA-Sharing-1.0:
https://www.kaggle.com/datasets/ealtman2019/ibm-transactions-for-anti-money-laundering-aml
It was generated by a different team with a different simulator, so unlike docs/evaluation.md the rules were not
designed around it. Nothing is tuned here: weights, thresholds and windows are the ones the app ships with.

Usage: python -I scripts/evaluate_external.py [--data DIR] [--days N]
  DIR must contain HI-Small_Trans.csv and HI-Small_Patterns.txt (they are not kept in this repository).
Writes docs/evaluation-external.md and docs/evaluation-external.json; scripts/evaluate.py summarises the latter.
"""
import argparse
import csv
import json
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.services.risk_engine import BAND_THRESHOLDS, LABELS, RULE_VERSION, assess_all  # noqa: E402

DEFAULT_DATA = Path.home() / ".cache" / "fraudgraph" / "external" / "ibm-aml"
SOURCE_URL = "https://www.kaggle.com/datasets/ealtman2019/ibm-transactions-for-anti-money-laundering-aml"
TS_FORMAT = "%Y/%m/%d %H:%M"


def load(path: Path, days: int) -> dict:
    """Read the first `days` calendar days. Self-transfers are left out because the app does not accept them."""
    rows, truth, raw = [], {}, {}
    per_day: Counter = Counter()
    currencies: set[str] = set()
    skipped_self = skipped_self_laundering = 0
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        next(reader)
        first_day = cutoff = None
        for n, r in enumerate(reader, start=1):
            ts = datetime.strptime(r[0], TS_FORMAT)
            per_day[ts.strftime("%Y-%m-%d")] += 1
            if first_day is None:
                # The file starts on its first day but is not strictly time-ordered within it.
                first_day = ts.replace(hour=0, minute=0)
                cutoff = first_day + timedelta(days=days)
            if not (first_day <= ts < cutoff):
                continue
            source, destination = f"{r[1]}:{r[2]}", f"{r[3]}:{r[4]}"
            laundering = r[10] == "1"
            if source == destination:
                skipped_self += 1
                skipped_self_laundering += laundering
                continue
            tx_id = f"IBM-{n:07d}"
            rows.append({"transaction_id": tx_id, "source_account": source, "destination_account": destination,
                         "amount": float(r[7]), "timestamp": ts, "device_id": None})
            truth[tx_id] = laundering
            currencies.add(r[8])
            if laundering:
                raw[",".join(r)] = tx_id
    return {"rows": rows, "truth": truth, "raw": raw, "per_day": dict(sorted(per_day.items())),
            "skipped_self": skipped_self, "skipped_self_laundering": skipped_self_laundering,
            "first_day": first_day, "cutoff": cutoff, "currencies": len(currencies)}


def pattern_types(path: Path, raw: dict[str, str]) -> dict[str, str]:
    """Map each laundering transfer in the slice to the typology the dataset authors documented for it."""
    out, current = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("BEGIN LAUNDERING ATTEMPT"):
            current = line.split(" - ", 1)[1].split(":")[0].strip().title()
        elif line.startswith("END LAUNDERING ATTEMPT"):
            current = None
        elif current and line.strip() in raw:
            out[raw[line.strip()]] = current
    return out


def confusion(pred: set[str], truth: dict[str, bool]) -> dict:
    tp = sum(1 for k, v in truth.items() if v and k in pred)
    fn = sum(1 for k, v in truth.items() if v and k not in pred)
    fp = len(pred) - tp
    tn = len(truth) - tp - fn - fp
    precision = tp / (tp + fp) if tp + fp else None
    base_rate = (tp + fn) / len(truth)
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn, "flagged": len(pred), "precision": precision,
            "recall": tp / (tp + fn) if tp + fn else None, "fpr": fp / (fp + tn) if fp + tn else None,
            "lift": precision / base_rate if precision is not None and base_rate else None}


def evaluate(data: dict, types: dict[str, str]) -> dict:
    rows, truth = data["rows"], data["truth"]
    t0 = time.perf_counter()
    assessments = assess_all(rows)
    engine_s = time.perf_counter() - t0

    medium = {k for k, a in assessments.items() if a["score"] >= BAND_THRESHOLDS["MEDIUM"]}
    high = {k for k, a in assessments.items() if a["score"] >= BAND_THRESHOLDS["HIGH"]}

    by_type: dict[str, list[str]] = defaultdict(list)
    for tx_id, laundering in truth.items():
        if laundering:
            by_type[types.get(tx_id, "Not in a documented pattern")].append(tx_id)
    typologies = [{"type": t, "laundering": len(ids), "flagged": sum(1 for i in ids if i in medium),
                   "max_score": max(assessments[i]["score"] for i in ids)}
                  for t, ids in sorted(by_type.items(), key=lambda kv: -len(kv[1]))]

    def signal_rates(ids: list[str]) -> dict[str, float]:
        counts = Counter(s["code"] for i in ids for s in assessments[i]["signals"])
        return {code: counts[code] / len(ids) if ids else 0.0 for code in LABELS}

    laundering_ids = [k for k, v in truth.items() if v]
    legit_ids = [k for k, v in truth.items() if not v]
    return {
        "dataset": "IBM Transactions for Anti Money Laundering, HI-Small", "source": SOURCE_URL,
        "license": "CDLA-Sharing-1.0", "rule_version": RULE_VERSION,
        "slice_start": data["first_day"].strftime("%Y-%m-%d"),
        "slice_end": (data["cutoff"] - timedelta(days=1)).strftime("%Y-%m-%d"),
        "file_transactions": sum(data["per_day"].values()), "transactions": len(rows),
        "accounts": len({r["source_account"] for r in rows} | {r["destination_account"] for r in rows}),
        "laundering": len(laundering_ids), "base_rate": len(laundering_ids) / len(rows),
        "skipped_self": data["skipped_self"], "skipped_self_laundering": data["skipped_self_laundering"],
        "currencies": data["currencies"], "engine_seconds": engine_s,
        "tx_level": {"MEDIUM+ (score >= 30)": confusion(medium, truth), "HIGH (score >= 60)": confusion(high, truth)},
        "typologies": typologies,
        "signal_rates": {"laundering": signal_rates(laundering_ids), "legitimate": signal_rates(legit_ids)},
    }


def pct(x, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x:.{digits}%}"


def render(m: dict) -> str:
    lines = [
        "# FraudGraph AI - Independent test (public dataset)",
        "",
        f"Rules `{m['rule_version']}`, unchanged, run on a dataset the team did not design: "
        f"[{m['dataset']}]({m['source']}) ({m['license']}). Generated by `python -I scripts/evaluate_external.py`.",
        "",
        "## Why this test exists",
        "",
        "[evaluation.md](evaluation.md) measures the rules on scenarios written by the same team that wrote the rules. "
        "This test removes that advantage. The data, the laundering patterns and the labels come from IBM's simulator, "
        "and no weight, threshold or window was adjusted for it.",
        "",
        "## Dataset slice",
        "",
        f"- Transfers from {m['slice_start']} to {m['slice_end']}: {m['transactions']:,} between {m['accounts']:,} accounts "
        f"(the full file has {m['file_transactions']:,}).",
        f"- Labeled laundering: {m['laundering']:,} transfers, {pct(m['base_rate'], 3)} of the slice.",
        f"- Left out: {m['skipped_self']:,} transfers from an account to itself "
        f"({m['skipped_self_laundering']} labeled laundering), which the app does not accept.",
        f"- Engine time to score the slice in-process: {m['engine_seconds']:.0f} s.",
        "",
        "## Transaction-level results",
        "",
        "| Threshold | Flagged | TP | FP | FN | Precision | Recall | FPR | Lift over base rate |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, c in m["tx_level"].items():
        lift = "n/a" if c["lift"] is None else f"{c['lift']:.1f}x"
        lines.append(f"| {name} | {c['flagged']:,} | {c['tp']:,} | {c['fp']:,} | {c['fn']:,} | {pct(c['precision'], 2)} | "
                     f"{pct(c['recall'])} | {pct(c['fpr'], 2)} | {lift} |")
    lines += ["", "Lift is precision divided by the base rate: how much more likely a flagged transfer is to be labeled "
              "laundering than one picked at random.",
              "", "## Recall by laundering pattern", "",
              "Pattern names are the ones the dataset authors documented in `HI-Small_Patterns.txt`.", "",
              "| Pattern | Laundering transfers | Flagged at MEDIUM+ | Recall | Highest score |", "|---|---|---|---|---|"]
    for t in m["typologies"]:
        lines.append(f"| {t['type']} | {t['laundering']:,} | {t['flagged']:,} | "
                     f"{pct(t['flagged'] / t['laundering'])} | {t['max_score']} |")
    lines += ["", "## How often each rule fired", "", "| Rule | On laundering transfers | On legitimate transfers |",
              "|---|---|---|"]
    for code, label in LABELS.items():
        lines.append(f"| {label} | {pct(m['signal_rates']['laundering'][code])} | "
                     f"{pct(m['signal_rates']['legitimate'][code])} |")
    lines += [
        "", "## How to read this", "",
        "- These numbers are much weaker than the ones in [evaluation.md](evaluation.md). That is the expected, honest "
        "result of testing on data the rules were not written for.",
        "- The rules look for money that moves on within 30 to 60 minutes. Many patterns in this dataset are spread over "
        "hours or days, so the time-window rules cannot see them.",
        "- The slice is the first days of the file. Accounts therefore have little or no earlier history, which weakens "
        "the unusual-amount baseline, and patterns that continue after the slice are cut short.",
        "- Timestamps have minute resolution and there are no device identifiers, so the shared-device rule never fires "
        "and transfers forwarded within the same minute are not counted as onward movement.",
        f"- Amounts are in {m['currencies']} currencies and are not converted. The fixed no-baseline threshold of 100,000 was chosen "
        "for rupees, so it means something different in each currency here.",
        "- The data is synthetic. It is independent of this project, but it is still not real bank data.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default=str(DEFAULT_DATA))
    parser.add_argument("--days", type=int, default=2)
    args = parser.parse_args()
    data_dir = Path(args.data)
    data = load(data_dir / "HI-Small_Trans.csv", args.days)
    print("transfers per day in the file:", data["per_day"], file=sys.stderr)
    metrics = evaluate(data, pattern_types(data_dir / "HI-Small_Patterns.txt", data["raw"]))
    (ROOT / "docs" / "evaluation-external.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    report = render(metrics)
    (ROOT / "docs" / "evaluation-external.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
